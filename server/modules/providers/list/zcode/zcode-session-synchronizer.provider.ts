import fsSync from 'node:fs';
import path from 'node:path';

import Database from 'better-sqlite3';

import { sessionsDb } from '@/modules/database/index.js';
import type { IProviderSessionSynchronizer } from '@/shared/interfaces.js';
import type { LLMProvider } from '@/shared/types.js';
import {
  getZCodeDatabasePath,
  normalizeProviderTimestamp,
  normalizeSessionName,
  readOptionalString,
} from '@/shared/utils.js';

const PROVIDER = 'zcode';

type ZCodeSessionRow = {
  id: string;
  directory: string | null;
  title: string | null;
  time_created: number | null;
  time_updated: number | null;
};

/**
 * Session synchronizer for ZCode's SQLite-backed session store.
 *
 * Implements the IProviderSessionSynchronizer interface to scan ZCode's
 * SQLite database and upsert normalized session metadata into the database.
 *
 * Key design decisions:
 * - Uses read-only SQLite access to avoid lock conflicts with running ZCode
 * - Short connections only - never holds write transactions
 * - Filters out sub-agent sessions (sess_subagent_agent_*)
 * - Uses title field directly (already generated by ZCode)
 * - Tracks high-water mark of time_updated for efficiency
 */
export class ZCodeSessionSynchronizer implements IProviderSessionSynchronizer {
  private readonly provider: LLMProvider = PROVIDER;

  /**
   * High-water mark for incremental synchronization.
   * Tracks the latest time_updated value seen across all sync operations.
   */
  private highWaterMarkTimeUpdated: number = 0;

  /**
   * Scans ZCode's SQLite database and upserts discovered sessions into DB.
   *
   * Queries top-level sessions (parent_id IS NULL) updated after `since`.
   * See the class docstring for the SQLite access discipline.
   */
  async synchronize(since?: Date): Promise<number> {
    const rows = this.queryUpdatedSessions(since?.getTime() ?? null, null);
    return rows.processedCount;
  }

  /**
   * Handles watcher changes for ZCode's SQLite database.
   *
   * Adapts the file-based watcher API to SQLite's database-level changes:
   * only `db.sqlite` / `db.sqlite-wal` events trigger a sync, which runs
   * incrementally from the in-memory high-water mark (capped at the most
   * recent 100 rows; the watcher's existing debouncing absorbs WAL write
   * frequency). Returns the first changed session id, or null.
   */
  async synchronizeFile(filePath: string): Promise<string | null> {
    const fileName = path.basename(filePath);

    if (fileName !== 'db.sqlite' && fileName !== 'db.sqlite-wal') {
      return null;
    }

    const sinceMillis = this.highWaterMarkTimeUpdated > 0 ? this.highWaterMarkTimeUpdated : null;
    const rows = this.queryUpdatedSessions(sinceMillis, 100);
    return rows.firstSessionId;
  }

  /**
   * Shared scan step for both sync entrypoints: opens a short read-only
   * connection, selects top-level non-subagent sessions with
   * `time_updated > sinceMillis`, upserts each row, and advances the
   * high-water mark.
   */
  private queryUpdatedSessions(
    sinceMillis: number | null,
    limit: number | null,
  ): { processedCount: number; firstSessionId: string | null } {
    const dbPath = getZCodeDatabasePath();
    if (!fsSync.existsSync(dbPath)) {
      return { processedCount: 0, firstSessionId: null };
    }

    let db: Database.Database | null = null;

    try {
      db = new Database(dbPath, { readonly: true, fileMustExist: true });

      const rows = db.prepare(`
        SELECT
          s.id AS id,
          s.directory AS directory,
          s.title AS title,
          s.time_created AS time_created,
          s.time_updated AS time_updated
        FROM session s
        WHERE s.parent_id IS NULL
          AND s.id NOT LIKE 'sess_subagent_agent_%'
          AND (? IS NULL OR s.time_updated > ?)
        ORDER BY s.time_updated DESC, s.id DESC
        ${limit === null ? '' : 'LIMIT ?'}
      `).all(...(limit === null ? [sinceMillis, sinceMillis] : [sinceMillis, sinceMillis, limit])) as ZCodeSessionRow[];

      let processedCount = 0;
      let firstSessionId: string | null = null;

      for (const row of rows) {
        const sessionId = this.upsertSession(row);
        if (sessionId) {
          processedCount += 1;
          firstSessionId ??= sessionId;
        }

        const timeUpdated = row.time_updated ?? row.time_created ?? 0;
        if (timeUpdated > this.highWaterMarkTimeUpdated) {
          this.highWaterMarkTimeUpdated = timeUpdated;
        }
      }

      return { processedCount, firstSessionId };
    } catch (error) {
      const message = error instanceof Error ? error.message : String(error);
      console.warn('[ZCodeProvider] Failed to synchronize sessions:', message);
      return { processedCount: 0, firstSessionId: null };
    } finally {
      if (db) {
        db.close();
      }
    }
  }

  /**
   * Upserts a single ZCode session into the sessions database.
   *
   * Uses the title field directly (already generated by ZCode) rather than
   * parsing it from transcript content. Binds provider-discovered rows to
   * pending app sessions, mirroring the opencode provider pattern.
   *
   * Note: `jsonl_path` stays null because ZCode shares one SQLite database
   * across sessions; pointing it at the database would risk deleting the
   * whole store when a single app session is removed.
   */
  private upsertSession(row: ZCodeSessionRow): string | null {
    const sessionId = readOptionalString(row.id);
    if (!sessionId) {
      return null;
    }

    // Filter out sub-agent sessions (double-check)
    if (sessionId.startsWith('sess_subagent_agent_')) {
      return null;
    }

    const projectPath = readOptionalString(row.directory);
    if (!projectPath) {
      return null;
    }

    const fallbackTitle = 'Untitled ZCode Session';
    const pendingAppSession = sessionsDb.getSessionByProviderSessionId(sessionId)
      ?? sessionsDb.getSessionById(sessionId)
      ?? sessionsDb.findLatestPendingAppSession(this.provider, projectPath);

    // Bind provider session id to pending app session if exists
    if (pendingAppSession && !pendingAppSession.provider_session_id) {
      sessionsDb.assignProviderSessionId(pendingAppSession.session_id, sessionId);
    }

    // Resolve existing session
    const existingSession = sessionsDb.getSessionByProviderSessionId(sessionId)
      ?? sessionsDb.getSessionById(sessionId);
    const existingName = existingSession?.custom_name;

    // Use existing name or ZCode's generated title
    const nextName = existingName && existingName !== fallbackTitle
      ? existingName
      : readOptionalString(row.title) ?? fallbackTitle;

    return sessionsDb.createSession(
      sessionId,
      this.provider,
      projectPath,
      normalizeSessionName(nextName, fallbackTitle),
      normalizeProviderTimestamp(row.time_created),
      normalizeProviderTimestamp(row.time_updated ?? row.time_created),
      null, // jsonl_path is null for SQLite-backed providers
    );
  }
}
